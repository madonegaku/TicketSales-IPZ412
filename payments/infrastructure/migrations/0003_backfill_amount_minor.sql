-- 0003 – ПЕРЕНЕСЕННЯ ДАНИХ: копійки для рядків, записаних до паралельного запису.
-- Виконується, коли всі екземпляри payments уже пишуть обидва стовпці (версія після 0002):
-- нові рядки мають amount_minor, тож заповнити лишається тільки старі.
-- Точність: amount має не більше двох знаків після коми, а double зберігає цілі числа точно
-- до 2^53, тож ROUND(amount * 100) дає точну кількість копійок для сум до 10^13 грн.
UPDATE payments
SET amount_minor = CAST(ROUND(CAST(amount AS REAL) * 100) AS INTEGER)
WHERE amount_minor IS NULL;
